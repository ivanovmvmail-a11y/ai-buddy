#!/bin/sh
set -eu
export GRAFANA_SQL_PASSWORD="$(cat /run/grafana-secret/password)"
if [ -n "${GRAFANA_ADMIN_USER:-}" ] && [ -n "${GRAFANA_ADMIN_PASSWORD:-}" ]; then
    export GF_SECURITY_ADMIN_USER="$GRAFANA_ADMIN_USER" GF_SECURITY_ADMIN_PASSWORD="$GRAFANA_ADMIN_PASSWORD"
    export GF_SECURITY_DISABLE_INITIAL_ADMIN_CREATION=false GF_AUTH_ANONYMOUS_ENABLED=false GF_AUTH_DISABLE_LOGIN_FORM=false
else
    export GF_SECURITY_DISABLE_INITIAL_ADMIN_CREATION=true GF_AUTH_ANONYMOUS_ENABLED=true GF_AUTH_DISABLE_LOGIN_FORM=true
fi
unset GRAFANA_ADMIN_USER GRAFANA_ADMIN_PASSWORD
exec /run.sh
